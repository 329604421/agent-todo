/**
 * 业务错误码 —— 与《技术开发文档-01 V1.2》§6.1 的错误码表逐字对齐。
 * 铁律：**业务错误一律 code != 0 ＋ HTTP 200**；只有系统级错误才返回 4xx/5xx。
 * 这样前端只要判 `code` 一个字段，不用同时处理"HTTP 状态码"与"业务码"两套语义。
 */
export const CODE = {
  OK: 0,

  /** 未登录 / token 失效 —— 前端应静默重新 wx.login 换 token 后重试一次 */
  UNAUTHORIZED: 1001,
  /** 不在白名单 —— 前端显示「暂无使用权限」页，**不重试** */
  NOT_ALLOWED: 1002,

  /** 参数校验失败 —— 表单内联报错 */
  BAD_PARAM: 2001,
  /** 资源不存在 —— ⚠️ 触发前端「记忆失效」分支（清空该模块详情记忆 ＋ 弹列表抽屉） */
  NOT_FOUND: 2002,
  /** 无权访问该资源（跨用户）—— 同 2002 处理，但**要记日志**（可能是越权尝试） */
  FORBIDDEN: 2003,
  /** 冲突（如项目色已被占用）—— 表单内联报错 */
  CONFLICT: 2004,
  /** 业务规则拒绝（如归档项目下新建脑图）—— 轻提示 */
  REJECTED: 2005,

  /** 文件过大 / 类型不支持 */
  FILE_INVALID: 3001,

  /** 服务端错误 —— 「服务开小差了」，**不自动重试** */
  SERVER: 5000,
} as const;

export type CodeValue = (typeof CODE)[keyof typeof CODE];
