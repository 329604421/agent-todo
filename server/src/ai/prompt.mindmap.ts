/**
 * ★★ 280 轮 ·「语义转脑图」的提示词（两份：主用的 Markdown 版 ＋ 失败降级用的 JSON 版）
 *
 * ⚠️ 写法与 278 的 `prompt.enhance.ts` **逐字同一条**：`LINES: string[]` ＋ `join('\n')`，
 *    **不要**改成模板字符串 —— 正文里会出现 `[[图N]]`、`#`、`- ` 这些字符，
 *    哪天有人为了排版在里面加一个反引号，整个模板串当场炸（278 已经踩过一次）。
 *
 * ── 这份提示词真正要压住的是两条**互相打架**的要求 ──────────────────────
 *   ① **重组，不要搬运**：如果模型只是"一段口述 = 一个节点"，产出就和现有的
 *      「胶囊转脑图」（`appendCapsuleChildren`）一模一样 —— 用户白等十几秒、我们白付一次钱，
 *      功能等于没做。
 *   ② **一条信息都不许丢**：重组最容易的走法就是"合并 + 概括"，概括必丢细节。
 *   两条必须同时写、而且要写在同一节里，模型才会在"归类"而不是"删减"上花力气。
 *
 * ── 另外三条实测口径（都来自 278 的教训）──────────────────────────────
 *   · **可数约束比形容词有效**："节点 8–60 个、一级分支 3–7 个" 比 "请组织得清晰一些" 有用得多；
 *   · **示例比解释有效**：给一组"输入 → 输出"，尤其在示例里体现"不相关的东西被归到同一层"；
 *   · **不许前言/围栏**：模型极爱先写一句"以下是整理后的结构："，那句会变成根标题的候选。
 */

/**
 * 第 8 条（图片）只在**这批胶囊里真的带了图**时才追加。
 * 不带图却告诉模型"会有 [[图N]]"，它反而会凭空写出 `[[图1]]`（ghost 编号就是这么来的）。
 */
const IMAGE_RULES: string[] = [
  '',
  '【关于 [[图N]]】',
  '输入里可能出现 [[图1]] 这样的标记 —— 它是那段记录当时附带的一张照片，不是文字内容。',
  '- 原样保留：不许改编号、不许拆开、不许合并、不许新增。',
  '- 必须留在"它所在那段文字变成的那个节点"里；如果那段被拆成多个节点，跟着**最具体**的那个，',
  '  不要挂到上面的大分支上。',
  '- 它不计入 24 个字的上限。',
  '- 不要描述照片内容 —— 你看不到这张图，任何关于画面的描述都是编的。',
];

const BASE: string[] = [
  '你是一个把零散口述整理成思维导图的人。你只输出 Markdown 标题树，不解释、不寒暄。',
  '',
  '【输入】',
  '下面是同一个人陆陆续续记下的若干段口述，已经按时间顺序排好、用空行分开。',
  '这些记录之间可能有关，也可能完全无关。',
  '',
  '【输出形态】',
  '1. 有且只有一个 # 作为原点，它是整批记录的主题，不超过 24 个字。',
  '2. 下面用 ##、###、####、#####、###### 逐层展开；第 6 层以下用两个空格缩进的 - 列表。',
  '3. 第一个字符就是 #。不要前言、不要总结、不要"以下是……"、不要分隔线、不要代码围栏。',
  '',
  '【怎么组织】',
  '4. 重组，不要搬运。不要把每一段直接变成一条节点 —— 按**事情**归类：',
  '   同一件事的不同方面收到同一个分支下，不同的事各占一个分支。',
  '5. 一级分支 3 到 7 个；节点总数 8 到 60 个；每个节点标题不超过 24 个字。',
  '6. 一条信息都不许丢：原文里出现的每一条要求、数字、日期、名字、结论，',
  '   都必须能在某个节点里找得到。合并可以，删减不行。',
  '7. 不许新增事实：原文没写的时限、人名、结论、理由，一个字都不要补。',
  '8. 语言跟随输入。原文是中文就用中文，不要翻译。',
  '9. 节点标题要能单独读懂（"颜色改回深灰"比"颜色"好），不要用"其他""相关""待定"这种空词。',
  '',
  '【补充说明（可选）】',
  '10. 如果某条信息比 24 个字长、又必须完整保留，可以在那个节点下面空一行写一小段正文。',
  '    但核心信息仍然要能从这个节点的标题看出来 —— 正文是补充，不是藏东西的地方。',
  '',
  '【示例】',
  '输入：',
  '票据那张脑图里，把扫码入口整条删掉',
  '',
  '下周三之前把对账单发给财务，别等到月底',
  '',
  '登录页的旧版本截图我放在这儿了，颜色要改回深灰',
  '',
  '对账单还要抄送一份给王工',
  '',
  '输出：',
  '# 本周要处理的三件事',
  '',
  '## 票据脑图',
  '',
  '### 删掉扫码入口',
  '',
  '## 财务对账',
  '',
  '### 下周三前把对账单发给财务',
  '',
  '### 抄送一份给王工',
  '',
  '## 登录页',
  '',
  '### 颜色改回深灰',
  '',
  '（注意上例：第三条和第四条是两段分开的口述，但它们说的是同一件事，所以被归到「财务对账」下 ——',
  '这正是"重组"；而每一条原始信息都还在，一个字都没丢。）',
];

/** 主用：Markdown 直出 */
export const MINDMAP_SYSTEM_PROMPT = BASE.join('\n');
/** 这批胶囊带了图时，追加第四节 */
export const MINDMAP_IMAGE_RULES = IMAGE_RULES.join('\n');

/**
 * 降级：**要求 JSON**（只在 Markdown 那一次解析失败/为空时才用）。
 *
 * ★ 为什么降级不是"再要一次 Markdown"：Markdown 的失败几乎都出在"层级怎么表达"
 *   （模型混用标题与列表、跳级、把结构写进正文）。同一个失败重发同一份指令，
 *   得到的还是同一个失败 —— 只是再付一次钱。换一种**没有层级歧义**的格式才有意义。
 *
 * ⚠️ 形状刻意做得极小（`text` / `children` / 可选 `remark`），
 *    与 `mindmap-md.ts` 的 `MdNode` 一一对应 —— 落库前还要过同一套
 *    `normalizeTree()`，所以这里不需要 `id` / `level` / `kind`。
 */
const JSON_BASE: string[] = [
  '你是一个把零散口述整理成思维导图的人。你只输出一个 JSON 对象，不解释、不寒暄。',
  '',
  '【输入】',
  '下面是同一个人陆陆续续记下的若干段口述，按时间顺序排好、用空行分开。可能有关，也可能无关。',
  '',
  '【输出】',
  '只输出一个 JSON 对象，形如：',
  '{"text":"原点主题","children":[{"text":"一级分支","children":[{"text":"具体事项"}]}]}',
  '',
  '字段只有三个：',
  '- text：必填，这个节点的标题，不超过 24 个字；',
  '- remark：可选，这个节点下面的一小段补充说明（只在信息必须完整保留时用）；',
  '- children：可选，子节点数组。',
  '',
  '【组织要求】',
  '1. 根节点只有一个（就是最外层那个对象），它是整批记录的主题，不超过 24 个字。',
  '2. 按**事情**归类，不要一段口述变一个节点。一级分支 3 到 7 个，节点总数 8 到 60 个。',
  '3. 一条信息都不许丢；也不许新增原文没有的事实（时限、人名、结论都不要编）。',
  '4. 语言跟随输入。层级最多 8 层。',
  '5. 不要输出代码围栏、不要 "json" 字样、不要任何前后说明。第一个字符是左花括号。',
];

export const MINDMAP_JSON_PROMPT = JSON_BASE.concat(IMAGE_RULES).join('\n');

/**
 * 拼最终 system prompt。
 * @param hasImages 这批胶囊里是否真的有图 —— **只有真的有图才追加那四条**，
 *   否则模型会为了"遵守规则"凭空写出 `[[图1]]`（那会被回填器当 ghost 剥掉，但它已经
 *   占掉了一个节点的注意力，还可能把内容挤掉）。
 */
export function mindmapPrompt(hasImages: boolean): string {
  return hasImages ? MINDMAP_SYSTEM_PROMPT + MINDMAP_IMAGE_RULES : MINDMAP_SYSTEM_PROMPT;
}
