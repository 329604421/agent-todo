-- 闪念胶囊**挂一张图**（★★ 263 轮 · 清单 H1）
--
-- ★ 需求与设计来源：`文档/闪念胶囊-手机端-原型对齐优化清单-263.md` H1–H5。
--   卡片上的图是"这条闪念当场拍下的那张截图"，上限 **1 张**
--   （原型底部原话：「只挂 1 张，选新的会替换掉当前的」）。
--
-- ★ 只加一列 `agenttodo_capsule.image_uri`（可空）。
--   · `NULL`   ＝ 没挂图（**所有既有行都是这一档** ⇒ 语义与改前逐行一致）
--   · 非 NULL  ＝ `POST /files` 返回的**相对 uri**（形如 `2026/10/ab12cd.jpg`）
--
-- ★ 纯新增可空列，**不改任何既有列、不动任何既有数据、不需要回填**（对线上是安全变更）。
--
-- ★ 为什么不照着 `agenttodo_todo_image` 再建一张表：
--   ① 上限就是 1 ⇒ 一张 1:N 的表会允许"两条图挂同一格"这种非法态；
--   ② "换图"在一张表里是"删旧 + 插新"两步，中间那一帧可能一条都没有；
--   ③ 胶囊是全库最热的读路径（`GET /sync` 全量下发），少一张表就少一次 join。
--   将来真要放开多张，再建表并把这一列迁过去（`sort` 从 0 编号）。
--
-- ★ 列宽 512 与 `agenttodo_todo_image.uri` **同源**：两条路走的是同一个上传通道
--   （`POST /files` → `common/upload.ts` 的 `saveImage`），产出的路径结构完全一样。
--
-- ★ 不加索引：这一列**不进任何 WHERE 条件**，只在出参里回显（与 `todo_image` 的 `uri` 同待遇）。

-- AlterTable · 胶囊：挂一张图（相对 uri）
ALTER TABLE `agenttodo_capsule` ADD COLUMN `image_uri` VARCHAR(512) NULL;
