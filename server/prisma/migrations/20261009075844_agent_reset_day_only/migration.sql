-- 额度重置日：从「月-日」收成「日」（★ 第一百三十三轮）
--
-- 口径：各家 agent 都按**自然月**重置 ⇒ 月份是个常量，只记「每月几号」。
-- 旧值形如 '10-01' / '09-30'（两位月 - 两位日），新值是 '01'–'31'。
--
-- ⚠️ 幂等：只匹配**严格 MM-DD 形状**的旧值 ⇒ 已经是两位日的不动，可重复执行。
--    特意不写成"取最后两位"：那会把更早的完整时间戳（'2026/10/15 13:54:03'）
--    切成秒（'03'）。前端 `store.resetDayOf()` 仍兼容解析那种老值，所以这里不碰它。
-- ⚠️ 纯数据迁移，不动任何列结构 ⇒ 不需要 `prisma generate`。
UPDATE `agenttodo_agent`
   SET `quota_reset_at` = RIGHT(`quota_reset_at`, 2)
 WHERE `quota_reset_at` REGEXP '^[0-9]{2}-[0-9]{2}$';
