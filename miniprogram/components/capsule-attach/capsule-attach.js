/**
 * 挂图（★★ 263 轮 · 清单 F3）—— 闪念胶囊**创建面板**与**编辑面板**共用这一块。
 *
 * ── 为什么要抽成组件 ─────────────────────────────────────────────────────
 * 清单一句话："两块面板各挂一次 —— 否则『改提示文案要改两处』，
 * 正是 259 轮官网那种分叉病。"
 * 而这两块面板的图区**必须逐像素同款**（用户来回切换时不该看到两种尺寸 /
 * 两句不一样的话），所以连文案一起收在这里：**只有这一份**。
 *
 * ── 职责边界（故意的）────────────────────────────────────────────────────
 * 它**只管画**：选图、上传、失败重试、关面板作废回调——全在父组件
 * （`components/capsule/capsule.js` 的 `_attachPick` / `_attachRemove`）。
 * 为什么不上移：上传态（`uploading`）、两个数据字段（uri / url）、
 * 以及"上传中不许保存"那道闸门，都在父组件的面板状态机里 ——
 * 让子组件也持有一份，就等于有两个地方知道"这张图传完了没有"。
 * ⇒ 输入 `url` ＋ `uploading`，输出两个事件（`pick` / `remove`），仅此而已。
 *
 * ── 三态（清单 H3 + 原型 `renderAttach`）─────────────────────────────────
 *   ① 空    —— 虚线坑「加截图」＋ 提示「最多挂 1 张图，留住截图里的现场」
 *   ② 上传中 —— 缩略图上盖霜白 ＋ 转圈 ＋「上传中…」，提示换成「正在上传…」
 *   ③ 已挂   —— 缩略图（点它＝**换图**）＋ 右下「更换」条 ＋ 右上 ✕（＝撤掉）
 *              ＋ 提示「已挂 1 张图，点图更换 · ✕ 移除」
 *
 * ⚠️ 点缩略图是**换图**、不是看大图（原型也是这么做的）。看大图在**列表卡片**上
 *    （`onPreviewImg` → `wx.previewImage`）；面板里正在编辑，用户要的是"换一张"。
 * ⚠️ 上传中**不给点**：那时候换图会发出第二个上传请求，而回来的是两张，
 *    谁后到谁生效 —— 用户看到的图与他最后一次选的那张不一定同一张。
 */
Component({

  /* ⚠️ **不声明 `styleIsolation`**（与 `drawer` / `form-drawer` 同一种做法）。
     理由：本组件的样式只用**自定义属性**（`var(--text-2)` / `var(--chip)` / `var(--hairline-strong)`…），
     而自定义属性靠**继承**往下传 —— 它不经过样式隔离（隔的是**选择器**，不是继承）。
     ⇒ `app.wxss` 的 `page{}` 里那套令牌照旧到位；`capsule` 的 `apply-shared`
        也不必"传"给它。反过来若哪天这里要借用外层某个**类**（`.cs-*` / `.ep-*`），
        那才需要 `apply-shared` —— 届时写进 `capsule-attach.json`（与 `capsule.json` 同一位置），
        **不要在这里再写一份**（同一个配置两处写法，改一处就有一处悄悄不生效）。 */

  properties: {
    /** 喂 `<image src>` 的那个：本地临时路径（上传中）或服务端完整 URL（已挂） */
    url: { type: String, value: '' },
    /** 正在上传 —— 挡点击 ＋ 盖上那层霜白 */
    uploading: { type: Boolean, value: false }
  },

  methods: {
    /** 点坑 / 点缩略图（＝加图 / 换图）—— 交给父组件去弹相册 */
    onPick: function () {
      if (this.data.uploading) return;
      this.triggerEvent('pick');
    },
    /** 点右上那个 ✕ —— 撤掉这张图（只改本地草稿，父组件保存时才落库） */
    onRemove: function () {
      if (this.data.uploading) return;
      this.triggerEvent('remove');
    }
  }
});
